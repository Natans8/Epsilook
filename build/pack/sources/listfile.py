"""File data id to asset path, from the community listfile.

Revalidated on every build, unlike every other source here: the listfile keeps
growing for builds already shipped, so a file id with no name last month may
have one today. The release tag is the cheap oracle -- one API call, and the
body is refetched only when the tag moved.

One listfile serves the whole roster. It is keyed on a file id, which is global
and stable across builds, so the name a file id gets does not depend on which
build is being packed; the only per-build thing is which subset of ids that
build's spell data points at. Every shipped pack agreeing on every name it
shares is therefore a property of the source rather than a coincidence worth
checking for.
"""

from __future__ import annotations

import json
import urllib.request

from .cache import BUILD_DIR, CACHE_DIR, Revalidated, tracked_source
from .source import Fetched, Origin, Source

LISTFILE_RELEASE_API = "https://api.github.com/repos/wowdev/wow-listfile/releases/latest"

LISTFILE_ASSET = "community-listfile-withcapitals.csv"
"""Which of the release's listfiles to take.

Two axes, and both are decided by what the pack is for. Community over
verified, because verified carries only hash-confirmed names and drops roughly
half of them -- a name we do not have is an asset a reader cannot find, which
is the opposite of the point. Capitals over the normalised lowercase, because
these paths are shown to a reader rather than only matched against: the two
files hold identical rows differing in case alone, most carry real casing, and
a vanishing few come back fully uppercase from the era when only the hash of an
uppercased path survived.

The casing is a display choice and never a matching one. Anything comparing
paths folds case at the comparison, so this constant cannot decide whether a
search finds something.
"""

SUPPLEMENT = BUILD_DIR / "sources" / "epsilon-listfile-supplement.csv.gz"
"""The vendored asset-name supplement: a private client's own names for the
assets it adds.

Vendored rather than fetched, and by decision rather than by necessity. Deriving
it takes a walk of the client's storage plus an in-game enumeration through an
API that answers only to a logged-in player, so it cannot be regenerated by a
build at all -- it costs somebody an evening, not a download. A tracked file
makes the cost visible and the result diffable: updating it is a re-run and a
patch, and an unchanged supplement re-vendors to identical bytes and stages
nothing.

Compressed because it is tracked. The same rows plain are some eight times the
size, and nothing reads them by hand.
"""

SUPPLEMENT_FLOOR = 18_000_000
"""The id below which a listfile supplement may not name anything.

Deliberately not the community listfile's highest id. That number grows on every
release, so bounding a supplement by it would hold only until the next one:
a private client's own name table carries stock ids as well as its own, and the
day the listfile grew past the recorded ceiling one of those stock rows would
start being admitted and would replace a real name with the client's spelling of
it.

This is the floor of the id space a private client allocates its own assets from.
That is a choice the client makes rather than an observation of a moving file, so
everything it adds sits above this and everything Blizzard ships sits below, and
a supplement confined by `above(SUPPLEMENT_FLOOR)` cannot shadow a community name
however far the listfile grows.
"""


def latest_release(api: str) -> tuple[str, str]:
    """The latest release's tag, and where its listfile asset is.

    The oracle a revalidated fetch asks before fetching anything: one small
    request, against a body of a hundred megabytes.

    Args:
        api: the releases endpoint to read.

    Returns:
        The release tag, and the asset's download url.

    Raises:
        LookupError: if the release carries no such asset. Told apart from an
            unreachable endpoint on purpose -- a release that stops carrying
            this asset reads as "the network is down" if both land in one
            message, and the build then runs on a cached listfile forever
            while reporting a problem nobody can act on.
        OSError: if the endpoint cannot be reached.
        ValueError: if what came back is not the document it should be.
    """
    request = urllib.request.Request(api, headers={"User-Agent": "epsilook-build"})
    with urllib.request.urlopen(request, timeout=60) as response:
        release = json.load(response)
    assets = {asset["name"]: asset["browser_download_url"]
              for asset in release["assets"]}
    if LISTFILE_ASSET not in assets:
        raise LookupError(f"release {release['tag_name']} carries no "
                          f"{LISTFILE_ASSET} (it has {', '.join(sorted(assets))})")
    return release["tag_name"], assets[LISTFILE_ASSET]


def listfile_source() -> Source:
    """The community listfile, revalidated against the latest release tag.

    Its origin is the endpoint the address is published at rather than the
    address itself: which asset url serves this file changes with every
    release, and the endpoint is the fixed thing a reader can go and look at.
    """
    into = CACHE_DIR / "listfile"
    return Fetched(
        name="listfile (wowdev/wow-listfile)",
        origin=Origin(LISTFILE_RELEASE_API, f"the {LISTFILE_ASSET} asset"),
        dest=into / LISTFILE_ASSET,
        fetch=Revalidated(resolve=latest_release,
                          token_file=into / "release-tag.txt"))


def supplement_source() -> Source:
    """The vendored asset-name supplement: in the checkout, or nowhere.

    No fetch can produce it, so acquiring it is the check that it is there.
    """
    return tracked_source("asset-name supplement", SUPPLEMENT)
